// Puente mínimo y explícito entre la interfaz y Windows.
const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("lap", {
  openPath: (p) => ipcRenderer.invoke("open-path", p),
  pathExists: (p) => ipcRenderer.invoke("path-exists", p),
  pickFolder: (start) => ipcRenderer.invoke("pick-folder", start),
  pickFile: (start) => ipcRenderer.invoke("pick-file", start),
  appInfo: () => ipcRenderer.invoke("app-info"),
  setTheme: (mode) => ipcRenderer.send("set-theme", mode),
  sessionLoad: () => ipcRenderer.invoke("session-load"),
  sessionSave: (raw) => ipcRenderer.invoke("session-save", raw),
  getAutostart: () => ipcRenderer.invoke("autostart-get"),
  setAutostart: (on) => ipcRenderer.invoke("autostart-set", on),
  notify: (title, body, route, urgent) => ipcRenderer.send("notify", title, body, route, !!urgent),
  showApp: () => ipcRenderer.send("show-window"),
  bigAlertShow: (data) => ipcRenderer.invoke("big-alert-show", data),
  bigAlertHide: (id) => ipcRenderer.send("big-alert-hide", id),
  bubbleSync: (st) => ipcRenderer.send("bubble-sync", st),
  bubbleNotify: (n) => ipcRenderer.send("bubble-notify", n),
  onBubbleAction: (fn) => ipcRenderer.on("bubble-action", (_e, a) => fn(a)),
  bubbleVisible: () => ipcRenderer.invoke("bubble-visible"),
  setBubbleVisible: (on) => ipcRenderer.invoke("bubble-set-visible", !!on),
  screenBusy: () => ipcRenderer.invoke("screen-busy"),
  setBadge: (dataUrl, count) => ipcRenderer.send("set-badge", dataUrl, count),
  onNavigate: (fn) => ipcRenderer.on("navigate", (_e, route) => fn(route)),
  updateStatus: () => ipcRenderer.invoke("update-status"),
  onUpdateReady: (fn) => ipcRenderer.on("update-ready", (_e, version) => fn(version)),
  installUpdate: () => ipcRenderer.send("update-install"),
  updateState: () => ipcRenderer.invoke("update-state"),
  checkUpdates: () => ipcRenderer.invoke("update-check"),
  onUpdateState: (fn) => ipcRenderer.on("update-state-changed", (_e, st) => fn(st)),
  hostStatus: () => ipcRenderer.invoke("host-status"),
  hostStart: () => ipcRenderer.invoke("host-start"),
  hostEnable: () => ipcRenderer.invoke("host-enable"),
  hostDisable: () => ipcRenderer.invoke("host-disable"),
  hostFirewall: () => ipcRenderer.invoke("host-firewall"),
  hostMaestro: (email, password, name) => ipcRenderer.invoke("host-maestro", email, password, name),
  discover: () => ipcRenderer.invoke("discover"),
  backupStatus: () => ipcRenderer.invoke("backup-status"),
  backupPick: () => ipcRenderer.invoke("backup-pick"),
  backupNow: () => ipcRenderer.invoke("backup-now"),
  backupOpen: () => ipcRenderer.invoke("backup-open"),
  backupRestore: (name) => ipcRenderer.invoke("backup-restore", name),
  onBackupChanged: (fn) => ipcRenderer.on("backup-changed", (_e, st) => fn(st)),
});
