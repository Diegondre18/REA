function applyStaticIcons(root) {
  root.querySelectorAll('[data-icon]').forEach(el => { el.innerHTML = icon(el.dataset.icon); });
  root.querySelectorAll('[data-icon-left]').forEach(el => {
    if (!el.dataset.iconDone) { el.innerHTML = icon(el.dataset.iconLeft) + '<span>' + el.textContent + '</span>'; el.dataset.iconDone = '1'; }
  });
}
